export type Locale = 'en' | 'zh-CN' | 'ja';
export type Copy = Translation;

export const locales: Locale[] = ['en', 'zh-CN', 'ja'];
export const localeNames: Record<Locale, string> = {
  en: 'English',
  'zh-CN': '简体中文',
  ja: '日本語',
};

export function isLocale(value: unknown): value is Locale {
  return typeof value === 'string' && (locales as string[]).includes(value);
}

// Browsers negotiate with language tags; anything untranslated falls back to
// English so a device locale can never blank the UI.
export function detectLocale(candidates: readonly string[]): Locale {
  for (const candidate of candidates) {
    const tag = candidate.toLowerCase();
    if (tag.startsWith('zh')) return 'zh-CN';
    if (tag.startsWith('ja')) return 'ja';
    if (tag.startsWith('en')) return 'en';
  }
  return 'en';
}

