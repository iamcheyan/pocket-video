import fs from 'node:fs';
const source=fs.readFileSync(new URL('../src/main.tsx',import.meta.url),'utf8');
const start=source.indexOf('const dict={');
if(start<0)throw new Error('Locale dictionary block not found');
const text=source.slice(start);
const markers=[...text.matchAll(/(['"]?)(en|zh-CN|ja)\1:\{/g)];
if(markers.length!==3)throw new Error(`Expected 3 locale dictionaries, found ${markers.length}`);
const locales=markers.map((m,i)=>{const from=m.index+m[0].length;const to=i+1<markers.length?markers[i+1].index:text.indexOf('} as const',from);const body=text.slice(from,to);return{name:m[2],keys:[...body.matchAll(/([A-Za-z][A-Za-z0-9]*):/g)].map(x=>x[1]).sort()}});
const baseline=locales[0].keys.join(',');
for(const locale of locales.slice(1))if(locale.keys.join(',')!==baseline)throw new Error(`${locale.name} translation keys differ from ${locales[0].name}`);
console.log(`i18n keys complete: ${locales.map(x=>`${x.name}=${x.keys.length}`).join(', ')}`);
